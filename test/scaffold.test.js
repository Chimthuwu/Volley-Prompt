// Scaffold core checks (todo B2): manifest validation (paths, caps, secrets), depth
// semantics, verdict parsing, and the todo.md handoff the next agent picks up cold.
const { test } = require('node:test');
const assert = require('node:assert');

const sc = require('../lib/scaffold.js');

const PROMPT = 'Build a keyboard-first daily planner. Constraints: local persistence only, no paid services. Tech stack: vanilla web.';

test('parseManifest accepts a clean manifest and reports the file count', () => {
  const r = sc.parseManifest('[{"path":"README.md","content":"# hi"},{"path":"src/app.js","content":"console.log(1)"}]');
  assert.ok(r.ok);
  assert.equal(r.files, 2);
  assert.equal(r.manifest[0].path, 'README.md');
});

test('parseManifest tolerates fenced output and surrounding prose', () => {
  const r = sc.parseManifest('Here you go:\n```json\n[{"path":"a.txt","content":"x"}]\n```\nDone.');
  assert.ok(r.ok, r.error);
  assert.equal(r.manifest[0].path, 'a.txt');
});

test('parseManifest rejects unsafe paths, duplicates, non-array JSON', () => {
  for (const bad of ['{"a":1}', '[]', '[{"path":"/abs/x","content":"y"}]', '[{"path":"../escape","content":"y"}]', '[{"path":"C:\\\\x","content":"y"}]', '[{"path":"a.txt","content":"1"},{"path":"a.txt","content":"2"}]']) {
    const r = sc.parseManifest(bad);
    assert.equal(r.ok, false, `expected rejection for ${bad}`);
    assert.ok(r.error && r.error.length < 300);
  }
});

test('parseManifest rejects oversized files, oversized totals and secrets', () => {
  const big = 'x'.repeat(sc.MAX_FILE_BYTES + 1);
  assert.equal(sc.parseManifest(`[{"path":"big.bin","content":"${big}"}]`).ok, false, 'per-file cap');
  const many = JSON.stringify(Array.from({ length: sc.MAX_FILES + 1 }, (_, i) => ({ path: `f${i}.txt`, content: 'x' })));
  assert.equal(sc.parseManifest(many).ok, false, 'file count cap');
  const withSecret = '[{"path":"config.js","content":"apiKey: sk-abc123"}]';
  assert.equal(sc.parseManifest(withSecret).ok, false, 'credential sniffing');
  // An example file with the same content is fine — scaffolds legitimately ship examples.
  const example = '[{"path":"config.example.js","content":"apiKey: sk-abc123"}]';
  assert.ok(sc.parseManifest(example).ok, 'example files may mention keys');
});

test('depth semantics are predictable, per todo L83', () => {
  assert.match(sc.cycleGoal(1, 3), /skeleton/);
  assert.match(sc.cycleGoal(2, 3), /stubs/);
  assert.match(sc.cycleGoal(3, 3), /milestone 1 end to end/);
  assert.match(sc.cycleGoal(3, 5), /milestone 1 end to end/, 'extra cycles keep hardening, not re-plan');
  assert.match(sc.cycleGoal(9, 2), /stubs/, 'cycle is clamped to the slider (cycle 9 of 2 behaves as 2)');
  assert.match(sc.authorUserContent({ cycle: 1, cycles: 3, idea: '', prompt: 'x' }), /cycle 1 of 3/, 'depth is stated in the model-facing content');
});

test('authorUserContent carries the approved prompt, depth and prior manifest', () => {
  const m = [{ path: 'PROMPT.md', content: PROMPT }];
  const c1 = sc.authorUserContent({ cycle: 1, cycles: 3, idea: 'planner', prompt: PROMPT });
  assert.match(c1, /APPROVED PROMPT:\nBuild a keyboard-first daily planner/);
  assert.match(c1, /cycle 1 of 3/);
  assert.ok(!c1.includes('CURRENT MANIFEST'), 'no manifest on cycle 1');
  const c2 = sc.authorUserContent({ cycle: 2, cycles: 3, idea: '', prompt: PROMPT, manifest: m });
  assert.match(c2, /CURRENT MANIFEST/);
  assert.match(c2, /PROMPT\.md/);
});

test('criticUserContent states the depth and embeds the manifest', () => {
  const c = sc.criticUserContent({ cycle: 2, cycles: 3, prompt: PROMPT, manifest: [{ path: 'a', content: 'b' }] });
  assert.match(c, /cycle 2 of 3/);
  assert.match(c, /MANIFEST TO REVIEW/);
  assert.match(c, /"path":"a"/);
});

test('verdictOf parses the shared FITNESS SCORE / VERDICT lines', () => {
  const v = sc.verdictOf('1. HIGH — no README.\nFITNESS SCORE: 48/100\nVERDICT: **REVISE**');
  assert.equal(v.score, 48);
  assert.equal(v.verdict, 'REVISE');
  const ok = sc.verdictOf('No issues.\nFITNESS SCORE: 92/100\nVERDICT: APPROVE');
  assert.equal(ok.verdict, 'APPROVE');
  assert.equal(sc.verdictOf('garbage').verdict, 'REVISE', 'no verdict line defaults to REVISE');
  assert.equal(sc.verdictOf('garbage').score, null);
});

test('buildTodoMd is a cold-start handoff: milestones, constraints, file list', () => {
  const manifest = [
    { path: 'package.json', content: '{}' },
    { path: 'PROMPT.md', content: PROMPT },
    { path: 'todo.md', content: 'generated by buildTodoMd itself' },
    { path: 'README.md', content: '# Daily Planner\nkeyboard-first' },
  ];
  const md = sc.buildTodoMd({ idea: 'planner app', prompt: PROMPT, cycles: 3, manifest });
  assert.match(md, /^# Daily Planner — build handoff/);
  assert.match(md, /## Milestones/);
  assert.match(md, /- \[ \] M1 — verify the scaffold/);
  assert.match(md, /no paid services/, 'constraints from the brief');
  assert.match(md, /- \[x\] `package\.json`/, 'created files are listed');
  assert.match(md, /dependency manifest is included/);
});
